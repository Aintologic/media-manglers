@dataclass(frozen=True, slots=True)
class WorkflowDefinition:
    number: str
    key: str
    title: str
    description: str
    supports_urls: bool
    requires_input: bool
    optimized_in_gui: bool
    launch_note: str

    @property
    def display_name(self) -> str:
        return f"{self.number} {self.title}"


