METADATA_BY_KEY = {item.key: item for item in SETTING_METADATA}


def normalize_workflow(value: Any) -> str:
    text = str(value or "").strip()
    if text in WORKFLOW_BY_NUMBER:
        return text
    if text in WORKFLOW_KEY_TO_NUMBER:
        return WORKFLOW_KEY_TO_NUMBER[text]
    lowered = text.lower()
    if lowered in {"review new videos", "5 review new videos"}:
        return WORKFLOW_REVIEW_NEW_VIDEOS
    for workflow in WORKFLOWS:
        if lowered in {workflow.title.lower(), workflow.display_name.lower()}:
            return workflow.number
    return DEFAULT_WORKFLOW


def metadata_for_workflow(workflow: str, *, include_advanced: bool = True) -> list[SettingMetadata]:
    number = normalize_workflow(workflow)
    return [
        item
        for item in SETTING_METADATA
        if number in item.workflows and (include_advanced or not item.advanced)
    ]
